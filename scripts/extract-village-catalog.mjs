// Extract the village kit's part CATALOG out of the built tool
// (public/village/index.html) into src/components/village/catalog.gen.ts,
// so the site can render exported scene recipes natively (the homepage
// map) without shipping or embedding the whole workshop.
//
// Usage:
//   node scripts/extract-village-catalog.mjs
//
// Re-running is safe and deterministic: the output is the tool's own JSON,
// re-emitted verbatim. Re-run after replacing public/village/index.html.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.join(__dirname, '..', 'public', 'village', 'index.html')
const OUT = path.join(__dirname, '..', 'src', 'components', 'village', 'catalog.gen.ts')

const html = fs.readFileSync(SRC, 'utf8')

// The tool authors CATALOG as a single JSON array literal on one line.
const m = html.match(/const CATALOG = (\[.*?\]);\n/s)
if (!m) {
  console.error('CATALOG literal not found in public/village/index.html')
  process.exit(1)
}
const catalog = JSON.parse(m[1])

const header = `// AUTO-GENERATED by scripts/extract-village-catalog.mjs — do not edit by hand.
// Source of truth: the CATALOG literal inside public/village/index.html
// (the onebit-kit Village Kit Builder). Re-extract after updating the tool.
//
// Each part is ASCII-authored pixel art: rows of characters, one per art
// pixel. '.' empty, 'X' ink, 'S' shade (dither), 'H' highlight (paper).

export interface VillagePart {
  name: string
  w: number
  h: number
  cat: string
  kind: string
  rows: string[]
  /** anchor: canopy attach px; top/stretch: trunk grow rules; drop: roof sink */
  meta?: { anchor?: [number, number]; top?: number; stretch?: number; drop?: number }
}

export const CATALOG: VillagePart[] = `

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, header + JSON.stringify(catalog, null, 1) + '\n')
console.log(`wrote ${OUT}: ${catalog.length} parts`)
