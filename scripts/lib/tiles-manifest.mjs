// Shared writers for the tile database (used by index-tiles.mjs and the /dev/tiles save endpoint).

import fs from 'node:fs'

export function writeManifest(file, meta, tiles) {
  // one tile per line keeps git diffs readable
  const body = tiles.map((t) => '  ' + JSON.stringify(t)).join(',\n')
  fs.writeFileSync(file, `{\n "meta": ${JSON.stringify(meta)},\n "tiles": [\n${body}\n ]\n}\n`)
}

export function writeIndex(file, meta, tiles) {
  const lines = tiles.map((t) => `  ${JSON.stringify(t.id)}: [${t.x}, ${t.y}, ${t.w}, ${t.h}],`)
  fs.writeFileSync(file, `// GENERATED by scripts/index-tiles.mjs. Do not edit; use /dev/tiles or scripts/tiles/regions.mjs.
export { TILE_META } from './tileSheet'

/** id -> [col, row, widthInCells, heightInCells] */
export const TILES = {
${lines.join('\n')}
} as const satisfies Record<string, readonly [number, number, number, number]>

export type TileId = keyof typeof TILES
`)
}

/** Sheet geometry only — tiny, so components can draw a sprite without pulling in the 5k-entry index. */
export function writeSheet(file, meta) {
  fs.writeFileSync(file, `// GENERATED by scripts/index-tiles.mjs. Do not edit.
export const TILE_META = ${JSON.stringify(meta)} as const
`)
}

/** Compact runtime data for the public atlas page: { meta, cats: { category: { sub: [[name,x,y,w?,h?]] } } }. */
export function writeAtlas(file, meta, tiles) {
  const cats = {}
  for (const t of tiles) {
    const sub = t.sub || 'misc'
    cats[t.category] ??= {}
    cats[t.category][sub] ??= []
    cats[t.category][sub].push(t.w > 1 || t.h > 1 ? [t.name, t.x, t.y, t.w, t.h] : [t.name, t.x, t.y])
  }
  fs.writeFileSync(file, JSON.stringify({ meta, cats }))
}
