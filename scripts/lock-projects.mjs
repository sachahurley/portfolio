// Encrypt the plaintext case-study bodies in content/locked/*.json into
// src/data/lockedBlocks.gen.ts (PBKDF2-SHA-256 -> AES-GCM-256). The plaintext
// files are gitignored; only the generated ciphertext module is committed, so
// locked write-ups never appear in the repo or the shipped bundle.
//
// Usage:
//   LOCK_PASSWORD=... node scripts/lock-projects.mjs
//   node scripts/lock-projects.mjs --password ...
//
// One shared password covers every locked project. The IV is derived from the
// slug + plaintext (first 12 bytes of their SHA-256), so re-running with the
// same password and content is deterministic: no diff churn. A nonce can only
// repeat when the plaintext is identical, in which case the ciphertext is
// identical too, so this leaks nothing beyond "the content didn't change".

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { webcrypto } from 'node:crypto'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const { subtle } = webcrypto

// KDF parameters; emitted into the generated module so the browser-side
// decrypt (src/lib/vault.ts) can never drift from the script.
const SALT = 'sh-vault-v1'
const ITERATIONS = 310000
const HASH = 'SHA-256'

const argv = process.argv.slice(2)
const pwArgIdx = argv.indexOf('--password')
const PASSWORD = pwArgIdx >= 0 ? argv[pwArgIdx + 1] : process.env.LOCK_PASSWORD

if (!PASSWORD) {
  console.error('No password. Pass LOCK_PASSWORD=... or --password <password>.')
  process.exit(1)
}

const contentDir = path.join(__dirname, '..', 'content', 'locked')
const outPath = path.join(__dirname, '..', 'src', 'data', 'lockedBlocks.gen.ts')

const files = fs.existsSync(contentDir)
  ? fs.readdirSync(contentDir).filter((f) => f.endsWith('.json')).sort()
  : []

if (files.length === 0) {
  console.error(`No plaintext sources found in ${contentDir} (expected <slug>.json files).`)
  process.exit(1)
}

const enc = new TextEncoder()

const baseKey = await subtle.importKey('raw', enc.encode(PASSWORD), 'PBKDF2', false, ['deriveKey'])
const key = await subtle.deriveKey(
  { name: 'PBKDF2', salt: enc.encode(SALT), iterations: ITERATIONS, hash: HASH },
  baseKey,
  { name: 'AES-GCM', length: 256 },
  false,
  ['encrypt'],
)

const entries = []
for (const file of files) {
  const slug = file.replace(/\.json$/, '')
  const parsed = JSON.parse(fs.readFileSync(path.join(contentDir, file), 'utf8'))
  if (!Array.isArray(parsed.blocks)) {
    console.error(`${file}: expected { "blocks": [...] }`)
    process.exit(1)
  }
  const plaintext = enc.encode(JSON.stringify(parsed.blocks))
  const digest = await subtle.digest('SHA-256', enc.encode(slug + JSON.stringify(parsed.blocks)))
  const iv = new Uint8Array(digest).slice(0, 12)
  const ct = await subtle.encrypt({ name: 'AES-GCM', iv }, key, plaintext)
  entries.push({
    slug,
    iv: Buffer.from(iv).toString('base64'),
    ct: Buffer.from(ct).toString('base64'),
  })
}

const body = entries
  .map((e) => `  '${e.slug}': {\n    iv: '${e.iv}',\n    ct: '${e.ct}',\n  },`)
  .join('\n')

const out = `// AUTO-GENERATED by scripts/lock-projects.mjs — do not edit by hand.
// Re-generate: LOCK_PASSWORD=... node scripts/lock-projects.mjs
// (plaintext sources live in content/locked/, gitignored; see its README)
//
// Each payload is the project's ProjectBlock[] as AES-GCM-256 ciphertext,
// keyed by a PBKDF2 derivation of the shared unlock password. Decryption
// happens in the browser via src/lib/vault.ts.

export const VAULT_KDF = {
  salt: '${SALT}',
  iterations: ${ITERATIONS},
  hash: '${HASH}',
} as const

export interface LockedPayload {
  iv: string // base64, 12 bytes
  ct: string // base64 ciphertext + GCM tag
}

export const lockedBlocks: Record<string, LockedPayload> = {
${body}
}
`

fs.writeFileSync(outPath, out)
console.log(`wrote ${outPath} (${entries.length} locked project${entries.length === 1 ? '' : 's'}: ${entries.map((e) => e.slug).join(', ')})`)
