/**
 * TAROT DATA
 *
 * The full 78-card deck for the tarot reader, plus the spread definitions.
 * Card ids mirror the baked tile id suffixes ('major/the_fool', 'wands/ace'),
 * and `tile` is always 'tarot/' + id, written out per entry so the data file
 * stays greppable. Meanings are grounded in the public-domain Rider-Waite
 * tradition but written fresh; each is a sentence fragment meant to sit
 * inside a template like "In what has passed, The Tower speaks of <meaning>".
 * keywordsUp/keywordsRev carry exactly three lowercase keywords each.
 */

export type Arcana = 'major' | 'minor'
export type TarotSuit = 'wands' | 'cups' | 'swords' | 'pentacles'

export interface TarotCard {
  /** stable id, mirrors the baked tile id suffix: 'major/the_fool', 'wands/ace', 'cups/10', 'swords/queen' */
  id: string
  name: string // 'The Fool', 'Ace of Wands', 'Ten of Cups', 'Queen of Swords'
  arcana: Arcana
  suit?: TarotSuit // minors only
  rank?: number // majors 0..21; minors 1..14 (1 ace, 2..10, 11 page, 12 knight, 13 queen, 14 king)
  keywordsUp: string[] // exactly 3 lowercase keywords/short phrases
  keywordsRev: string[] // exactly 3
  meaningUp: string // one sentence fragment, <= 20 words, no trailing period
  meaningRev: string // same form
  tile: string // 'tarot/' + id
}

